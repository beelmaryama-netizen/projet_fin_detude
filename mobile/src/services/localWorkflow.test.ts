import { beforeEach, describe, expect, it } from 'vitest';
import { createMockClientServices } from '../features/client/services/mockClientService';
import { createMockEmployeeService } from '../features/employee/services/mockEmployeeService';
import { useAdminStore, createAdminDemoData } from '../features/employer/store/adminStore';
import { clientBridge, employeeBridge, torontoInstant } from './localWorkflow';
import type { User } from '../types/identity';
import type { RequestSubmission } from '../features/requests/types/request';
const client: User = { id: 'client-e2e', email: 'client@example.com', firstName: 'Marie', lastName: 'Test', role: 'CLIENT' };
const employee: User = { id: 'employee-e2e', email: 'employee@magicpro.demo', firstName: 'Sarah', lastName: 'Test', role: 'EMPLOYEE' };
const day = () => new Date(Date.now() + 7 * 86400000).toISOString().slice(0, 10);
const input = (): RequestSubmission => ({ category: 'RESIDENTIAL', residential: { propertyType: 'HOUSE', bedrooms: 2, bathrooms: 1, floors: 1, areaSqft: '1000', hasPets: false, description: 'Nettoyer la cuisine', services: ['Cuisine', 'Fenêtres intérieures'], parking: 'Allée privée' }, photos: [{ id: 'client-photo', uri: 'file:///client.jpg', name: 'Client' }], schedule: { availabilities: [{ date: day(), slot: 'CUSTOM', startTime: '09:00', endTime: '12:00' }], instructions: 'Produits doux', accessNotes: 'Sonner', addressId: '' }, submissionKey: 'e2e' });
beforeEach(() => useAdminStore.setState({ ...createAdminDemoData(), ownerId: null }));
describe('shared client/admin/employee workflow', () => {
 it('runs a real local request → offer → assignment → report cycle', async () => {
  const clients = createMockClientServices({ latency: 0 }); clients.connect(clientBridge);
  const employees = createMockEmployeeService({ latency: 0 }); employees.connect(employeeBridge);
  const request = await clients.requests.create(client, input());
  expect(useAdminStore.getState().requests.find(r => r.id === request.id)?.dossier?.photos).toHaveLength(1);
  const estimate = useAdminStore.getState().saveEstimate({ requestId: request.id, durationHours: 2, employeeCount: 1, subtotal: '100', taxPercent: '15', date: day(), startTime: '09:00', endTime: '11:00', validityHours: 48, notes: 'Matériel inclus', requiresBeforePhotos: true, requiresAfterPhotos: true });
  if (!estimate.ok) throw Error(estimate.error);
  expect(useAdminStore.getState().sendOffer(estimate.value.id).ok).toBe(true);
  const quote = (await clients.quotes.list(client)).find(q => q.id === estimate.value.id)!;
  expect(quote.totalCents).toBe(11500); expect(quote.employeeCount).toBe(1);
  const reservation = await clients.quotes.accept(client, quote.id);
  const mission = useAdminStore.getState().missions.find(m => m.offerId === quote.id)!;
  expect(mission.checklist.some(t => t.label === 'Cuisine')).toBe(true);
  expect(useAdminStore.getState().assignMission(mission.id, 'EMP-001').ok).toBe(true);
  expect((await clients.reservations.get(client, reservation.id)).status).toBe('CONFIRMED');
  const detail = await employees.get(employee, mission.id);
  expect(detail.clientPhotos).toHaveLength(1); expect(detail.instructions).toContain('Allée privée');
  expect(detail).not.toHaveProperty('subtotalCents');
  await expect(employees.start(employee, { id: mission.id, photos: [] })).rejects.toThrow('photo');
  const photo = { id: 'before', uri: 'file:///before.jpg', phase: 'BEFORE' as const, createdAt: new Date().toISOString() };
  await employees.start(employee, { id: mission.id, photos: [photo] });
  expect((await clients.reservations.get(client, reservation.id)).status).toBe('IN_PROGRESS');
  await employees.toggle(employee, { id: mission.id, itemId: detail.checklist[0]!.id, isDone: true, note: 'Matériel vérifié' });
  await expect(employees.complete(employee, { id: mission.id, report: { note: '', incident: '' } })).rejects.toThrow('photo');
  await employees.addPhoto(employee, { id: mission.id, photo: { ...photo, id: 'after', phase: 'AFTER' } });
  await employees.complete(employee, { id: mission.id, report: { note: 'Prestation effectuée', incident: '' } });
  const completed = await clients.reservations.get(client, reservation.id);
  expect(completed.status).toBe('COMPLETED'); expect(completed.team).toContain('Sarah Martin');
  expect(completed.report).toBe('Prestation effectuée');
  expect(useAdminStore.getState().missions.find(m => m.id === mission.id)?.checklist[0]?.note).toBe('Matériel vérifié');
  expect((await clients.notifications.list(client)).length).toBeGreaterThan(3);
  await expect(employees.toggle(employee, { id: mission.id, itemId: detail.checklist[0]!.id, isDone: false })).rejects.toThrow();
  await expect(clients.requests.get({ ...client, id: 'stranger' }, request.id)).rejects.toThrow();
  await expect(employees.get({ ...employee, email: 'ahmed@magicpro.example' }, mission.id)).rejects.toThrow();
  const restored = createMockClientServices({ latency: 0 }); restored.restore(clients.snapshot()); restored.connect(clientBridge);
  expect((await restored.reservations.get(client, reservation.id)).report).toBe('Prestation effectuée');
 });
 it('rejects an assignment outside structured availability', () => {
  const state = useAdminStore.getState(); const mission = state.missions.find(m => m.id === 'MIS-001')!;
  useAdminStore.setState(s => ({ employees: s.employees.map(e => e.id === 'EMP-001' ? { ...e, workingHours: { days: [], start: '08:00', end: '18:00' } } : e) }));
  expect(useAdminStore.getState().assignMission(mission.id, 'EMP-001').ok).toBe(false);
 });
 it('converts Toronto times independently from device timezone and DST', () => {
  expect(torontoInstant('2026-07-10', '09:00')).toBe('2026-07-10T13:00:00.000Z');
  expect(torontoInstant('2026-12-10', '09:00')).toBe('2026-12-10T14:00:00.000Z');
 });
});
